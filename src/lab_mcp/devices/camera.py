from typing import Protocol, Callable
from ..models import CameraPatch, CaptureRequest, FrameRecord


class CameraAdapter(Protocol):
    def connect(self)->dict: ...
    def settings(self)->dict: ...
    def check_capture_ready(self)->None: ...
    def validate_patch(self,patch:CameraPatch)->None: ...
    def apply_settings(self,patch:CameraPatch)->dict: ...
    def capture(self,request:CaptureRequest,boundary_ns:int,on_frame:Callable[[FrameRecord],None])->dict: ...
    def status(self)->dict: ...
    def disconnect(self)->dict: ...
